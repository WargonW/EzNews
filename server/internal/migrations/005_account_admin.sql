-- ============================================================
-- 005 账号管理：停用账户 + 管理员可审计字段
--
-- 背景：user.role 列自建表起就存在（DEFAULT 'user'，注释写着"admin 预留"），
--       但从来没有任何代码设置或读取它 —— 是一把插在锁上没转过的钥匙。
--
-- 本迁移只加 **停用** 所需的字段。为什么必须加：
--   「停用」是一个**持久状态**，停用之后即便用户重新登录也必须继续被拒绝。
--   仅靠 token_version+1 只能把当前会话踢下线 —— 用户拿着正确的密码再登一次就进来了，
--   那不叫停用，那叫"注销一次"。
-- ============================================================

ALTER TABLE user ADD COLUMN disabled_at INTEGER;

-- ============ 索引：管理后台按状态筛选用户 ============
-- 列的取舍：NULL 表示未停用，非 NULL 是停用时刻（INTEGER 毫秒）。
-- 刻意**不设 NOT NULL DEFAULT 0** —— 用 NULL 表达"从未停用"更贴近语义，
-- 也省掉"0 到底是从未停用还是 Unix 纪元当天停用"这种歧义。
--
-- 部分索引（partial index）只索引已停用的行：绝大多数系统里停用是少数派，
-- 索引体积因此常年保持在极小值，而 "WHERE disabled_at IS NOT NULL" 的查询
-- 又能直接走索引。
CREATE INDEX IF NOT EXISTS idx_user_disabled ON user(disabled_at) WHERE disabled_at IS NOT NULL;
